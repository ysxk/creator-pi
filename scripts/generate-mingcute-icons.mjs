#!/usr/bin/env node
/*
 * Generates apps/desktop/src/components/mingcute-icons.generated.ts from the
 * pinned @iconify-json/mingcute package. Only the glyphs icons.tsx names via
 * `mingcute("<base>")` are emitted, each as a `-line` and a `-fill` variant,
 * so the renderer ships no icon runtime, no full icon set, and never fetches
 * icons over the network (the renderer CSP forbids it).
 *
 * Run after changing the glyphs icons.tsx uses:
 *   node scripts/generate-mingcute-icons.mjs
 * Pass --check to fail when the committed file is stale.
 */
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("..", import.meta.url));
const iconsSource = join(root, "apps/desktop/src/components/icons.tsx");
const output = join(root, "apps/desktop/src/components/mingcute-icons.generated.ts");
const require = createRequire(join(root, "apps/desktop/package.json"));
const pkg = require("@iconify-json/mingcute/package.json");
const collection = require("@iconify-json/mingcute/icons.json");

const ATTRIBUTE_NAMES = {
  "clip-rule": "clipRule",
  "fill-opacity": "fillOpacity",
  "fill-rule": "fillRule",
  "stroke-dasharray": "strokeDasharray",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "stroke-miterlimit": "strokeMiterlimit",
  "stroke-opacity": "strokeOpacity",
  "stroke-width": "strokeWidth",
};
const ALLOWED_TAGS = new Set(["g", "path", "circle", "ellipse", "rect", "line", "polyline", "polygon"]);

function resolve(name) {
  let current = name;
  for (let depth = 0; depth < 8; depth += 1) {
    const icon = collection.icons[current];
    if (icon) return icon;
    const alias = collection.aliases?.[current];
    if (!alias) break;
    current = alias.parent;
  }
  throw new Error(`MingCute icon "${name}" is missing from @iconify-json/mingcute@${pkg.version}`);
}

/** Parses an Iconify body (a flat SVG fragment) into [tag, attrs, children] nodes. */
function parseBody(body, name) {
  const tokens = body.match(/<\/?[a-z]+[^>]*>/gi) ?? [];
  const rootNodes = [];
  const stack = [{ children: rootNodes }];
  for (const token of tokens) {
    if (token.startsWith("</")) {
      stack.pop();
      continue;
    }
    const [, tag, rest] = token.match(/^<([a-z]+)([^>]*?)\/?>$/i) ?? [];
    if (!ALLOWED_TAGS.has(tag)) throw new Error(`${name}: unsupported <${tag}>`);
    const attrs = {};
    for (const [, key, value] of rest.matchAll(/([a-z-]+)="([^"]*)"/gi)) {
      attrs[ATTRIBUTE_NAMES[key] ?? key] = value;
    }
    const node = [tag, attrs, []];
    stack.at(-1).children.push(node);
    if (!token.endsWith("/>")) stack.push({ children: node[2] });
  }
  return rootNodes;
}

/*
 * Lucide carried its stroke width on the <svg>, and callers and CSS still
 * override it there. Hoist a uniform stroke width off the paths so they
 * inherit it from the root again.
 */
function hoistStrokeWidth(nodes) {
  const widths = new Set();
  const visit = (list) => {
    for (const [, attrs, children] of list) {
      if (attrs.strokeWidth !== undefined) widths.add(attrs.strokeWidth);
      visit(children);
    }
  };
  visit(nodes);
  if (widths.size !== 1) return { nodes, strokeWidth: undefined };
  const strip = (list) =>
    list.map(([tag, attrs, children]) => {
      const { strokeWidth: _, ...rest } = attrs;
      return [tag, rest, strip(children)];
    });
  return { nodes: strip(nodes), strokeWidth: Number([...widths][0]) };
}

function compact(nodes) {
  return nodes.map(([tag, attrs, children]) =>
    children.length ? [tag, attrs, compact(children)] : [tag, attrs],
  );
}

const source = await readFile(iconsSource, "utf8");
const bases = [...new Set([...source.matchAll(/mingcute\("([a-z0-9-]+)"/g)].map((m) => m[1]))].sort();
if (bases.length === 0) throw new Error("icons.tsx names no mingcute(\"…\") glyphs");

const entries = [];
for (const base of bases) {
  for (const variant of ["line", "fill"]) {
    const name = `${base}-${variant}`;
    const icon = resolve(name);
    const width = icon.width ?? collection.width ?? 24;
    const height = icon.height ?? collection.height ?? 24;
    const { nodes, strokeWidth } = hoistStrokeWidth(parseBody(icon.body, name));
    const glyph = { viewBox: `0 0 ${width} ${height}`, nodes: compact(nodes) };
    if (strokeWidth !== undefined) glyph.strokeWidth = strokeWidth;
    entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(glyph)},`);
  }
}

const text = `/*
 * @generated by scripts/generate-mingcute-icons.mjs — do not edit by hand.
 * MingCute Icon ${pkg.version} (https://github.com/Richard9394/MingCute),
 * Apache License 2.0. Only the glyphs icons.tsx uses are included.
 */
export type MingcuteNode =
  | readonly [tag: string, attrs: Readonly<Record<string, string>>]
  | readonly [tag: string, attrs: Readonly<Record<string, string>>, children: readonly MingcuteNode[]];

export type MingcuteGlyph = {
  readonly viewBox: string;
  readonly nodes: readonly MingcuteNode[];
  /** Uniform stroke width hoisted onto the <svg>; absent for fill-only glyphs. */
  readonly strokeWidth?: number;
};

export const MINGCUTE_GLYPHS: Readonly<Record<string, MingcuteGlyph>> = {
${entries.join("\n")}
};
`;

if (process.argv.includes("--check")) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== text) {
    console.error("mingcute-icons.generated.ts is stale; run node scripts/generate-mingcute-icons.mjs");
    process.exit(1);
  }
  console.log(`mingcute icons up to date (${bases.length} glyphs)`);
} else {
  await writeFile(output, text);
  console.log(`wrote ${bases.length} glyphs (${entries.length} variants) to ${output}`);
}
